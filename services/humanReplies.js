const fs = require('fs');
const path = require('path');

const NAMES_FILE = path.join(__dirname, '..', 'config', 'player_names.json');
let playerNames = {};

// تحميل الأسماء المحفوظة
try {
  if (fs.existsSync(NAMES_FILE)) {
    playerNames = JSON.parse(fs.readFileSync(NAMES_FILE, 'utf8'));
  }
} catch (e) {
  playerNames = {};
}

// حفظ اسم اللاعب
function registerPlayer(userId, fullName) {
  if (!userId || !fullName) return;
  const cleanId = String(userId);
  const cleanName = String(fullName).trim();
  if (playerNames[cleanId] !== cleanName) {
    playerNames[cleanId] = cleanName;
    try {
      const dir = path.dirname(NAMES_FILE);
      if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(NAMES_FILE, JSON.stringify(playerNames, null, 2), 'utf8');
    } catch (_) {}
  }
}

// استخراج الاسم الأول أو اللقب اللطيف لجعل الرد بشرياً
function getFriendlyName(userId, fallback = '') {
  const cleanId = String(userId);
  const fullName = playerNames[cleanId] || fallback || '';
  if (!fullName) return '';
  // نأخذ أول كلمة فقط إذا كان اسماً مركباً أو ثلاثياً
  const firstWord = fullName.split(/\s+/)[0];
  return firstWord || fullName;
}

